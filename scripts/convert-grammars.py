#!/usr/bin/env python3
"""Converts the TextMate grammars in native/highlight/grammars/ to Sublime syntaxes (T-0189).

syntect, the highlighter's engine (ADR 0012), reads Sublime's .sublime-syntax only. Each folder
under native/highlight/grammars/ holds a TextMate grammar as JSON (`source.json`), its licence and
a `meta.json` naming the language; this writes `<folder>.sublime-syntax` beside them, which the
highlighter's build (native/highlight/build.rs) adds to bat's syntaxes. The output is generated:
change the source or this script, never the output.

Read-only apart from the outputs, standard library only. Run from the repository root:

    scripts/convert-grammars.py            # convert every folder
    scripts/convert-grammars.py --check    # fail if an output differs from a fresh conversion

How TextMate's rules map:

- `match` stays a match, with its `name` as the scope and its captures.
- `begin`/`end` becomes a match that pushes an anonymous context: `name` is its meta scope,
  `contentName` its content scope, `end` a match that pops (after the inner patterns when
  `applyEndPatternLast` is set). Backreferences in `end` refer to `begin`'s captures, as in
  Sublime.
- `begin`/`while` becomes the same, popping at the first line that doesn't start with `while`;
  an approximation, since Sublime syntaxes have no `while`.
- `include`: `#name` the repository entry (nearest enclosing repository first), `$self` and `$base`
  the grammar itself, another grammar's scope (`source.js`) that syntax by scope. One of another
  grammar's rules (`source.cs#type`) is the matching context of bat's syntax where `FOREIGN` names
  one, and that whole syntax otherwise (F-0263).
- A rule with `patterns` only becomes a context of its own, included where it stood.
- Captures keep their names. Sublime has no patterns inside a capture: a capture with patterns and
  no name gets the scope its patterns would give the whole capture, where `CAPTURE_SCOPES` or a
  one-rule repository entry (`#transition`: `@`) says what that is, and no scope otherwise.
- Scope names lose TextMate's `$1` placeholders (captured text, which Sublime doesn't substitute).
- `injections` are dropped.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRAMMARS = ROOT / "native" / "highlight" / "grammars"

# Other grammars' rules as contexts of bat's syntaxes (sublimehq/Packages, the commit bat pins).
# Only contexts that never pop or set: included in one of ours, those would end it early.
FOREIGN = {
    "source.cs#type": "scope:source.cs#type",
    "source.cs#attribute-section": "scope:source.cs#attribute",
    "source.cs#string-literal": "scope:source.cs#literals",
    "source.cs#boolean-literal": "scope:source.cs#literals",
    "text.html.basic#attribute": "scope:text.html.basic#tag-attributes",
}

# The scope a capture whose only pattern is one of these includes would give it whole.
CAPTURE_SCOPES = {
    "source.cs#type": "support.type.cs",
    "source.cs#string-literal": "string.quoted.double.cs",
    "source.cs#boolean-literal": "constant.language.boolean.cs",
}

PLACEHOLDER = re.compile(r"\.?\$(?:\d+|\{\d+:/\w+\})")


class Converter:
    """Converts one TextMate grammar."""

    def __init__(self, grammar: dict, meta: dict) -> None:
        self.grammar = grammar
        self.meta = meta
        self.contexts: dict[str, list] = {}
        self.anonymous = 0
        self.warnings: list[str] = []

    def convert(self) -> str:
        top = {"main": "main"}
        scopes = [top]
        repository = self.grammar.get("repository", {})
        names = self._name_repository(repository, "")
        top.update(names)
        for key, rule in repository.items():
            self.contexts[names[key]] = self._context_of(rule, scopes)
        self.contexts["main"] = self._rules(self.grammar.get("patterns", []), scopes)
        if self.grammar.get("injections"):
            self.warnings.append("injections dropped")

        lines = [
            "%YAML 1.2",
            "---",
            f"# Generated by scripts/convert-grammars.py from {self.meta['source']}; don't edit.",
            f"name: {dump(self.meta['name'])}",
            f"scope: {dump(self.grammar['scopeName'])}",
            "file_extensions:",
        ]
        lines += [
            f"  - {dump(extension)}" for extension in self.meta.get("extensions", [])
        ]
        if not self.meta.get("extensions"):
            lines[-1] = "file_extensions: []"
        lines.append("contexts:")
        for name in sorted(self.contexts, key=lambda n: (n != "main", n)):
            lines.append(f"  {name}:")
            lines += emit(self.contexts[name], 4) if self.contexts[name] else ["    []"]
        return "\n".join(lines) + "\n"

    def _name_repository(self, repository: dict, prefix: str) -> dict[str, str]:
        return {
            key: "r_" + re.sub(r"[^A-Za-z0-9_-]", "_", prefix + key)
            for key in repository
        }

    def _context_of(self, rule: dict, scopes: list[dict]) -> list:
        """A repository entry as a context: its patterns, or the rule itself."""
        if any(k in rule for k in ("match", "begin")):
            return self._rules([rule], scopes)
        return self._rules(
            rule.get("patterns", []), self._with_repository(rule, scopes)
        )

    def _with_repository(self, rule: dict, scopes: list[dict]) -> list[dict]:
        repository = rule.get("repository")
        if not repository:
            return scopes
        self.anonymous += 1
        names = self._name_repository(repository, f"n{self.anonymous}_")
        inner = [*scopes, names]
        for key, entry in repository.items():
            self.contexts[names[key]] = self._context_of(entry, inner)
        return inner

    def _rules(self, patterns: list, scopes: list[dict]) -> list:
        rules = []
        for pattern in patterns:
            rule = self._rule(pattern, scopes)
            if rule is not None:
                rules.append(rule)
        return rules

    def _rule(self, pattern: dict, scopes: list[dict]) -> dict | None:
        if pattern.get("disabled"):
            return None
        if "include" in pattern:
            return self._include(pattern["include"], scopes)
        scopes = self._with_repository(pattern, scopes)
        if "match" in pattern:
            rule = {"match": pattern["match"]}
            if pattern.get("name"):
                rule["scope"] = self.scope(pattern["name"])
            captures = self._captures(pattern.get("captures"))
            if captures:
                rule["captures"] = captures
            return rule
        if "begin" in pattern:
            return self._begin(pattern, scopes)
        if "patterns" in pattern:
            self.anonymous += 1
            name = f"group_{self.anonymous}"
            self.contexts[name] = self._rules(pattern["patterns"], scopes)
            return {"include": name}
        self.warnings.append(
            f"rule without match, begin or patterns: {sorted(pattern)}"
        )
        return None

    def _begin(self, pattern: dict, scopes: list[dict]) -> dict:
        context: list = []
        if pattern.get("name"):
            context.append({"meta_scope": self.scope(pattern["name"])})
        if pattern.get("contentName"):
            context.append({"meta_content_scope": self.scope(pattern["contentName"])})
        inner = self._rules(pattern.get("patterns", []), scopes)
        if "while" in pattern:
            keep = {"match": "^(?:" + pattern["while"] + ")"}
            captures = self._captures(
                pattern.get("whileCaptures") or pattern.get("captures")
            )
            if captures:
                keep["captures"] = captures
            # Sublime has no while: consume the marker at a line's start, pop at a line without it.
            context.append(keep)
            context.append({"match": "^(?!(?:" + pattern["while"] + "))", "pop": True})
            context += inner
        else:
            end = {"match": pattern.get("end", "$"), "pop": True}
            captures = self._captures(
                pattern.get("endCaptures") or pattern.get("captures")
            )
            if captures:
                end["captures"] = captures
            if pattern.get("applyEndPatternLast"):
                context += inner
                context.append(end)
            else:
                context.append(end)
                context += inner
        rule = {"match": pattern["begin"]}
        captures = self._captures(
            pattern.get("beginCaptures") or pattern.get("captures")
        )
        if captures:
            rule["captures"] = captures
        rule["push"] = context
        return rule

    def _include(self, target: str, scopes: list[dict]) -> dict | None:
        if target in ("$self", "$base"):
            return {"include": "main"}
        if target.startswith("#"):
            key = target[1:]
            for names in reversed(scopes):
                if key in names:
                    return {"include": names[key]}
            self.warnings.append(f"include of a missing repository entry: {target}")
            return None
        if target in FOREIGN:
            return {"include": FOREIGN[target]}
        if "#" in target:
            # Another grammar's rule with no context named for it: include the whole grammar.
            target = target.split("#", 1)[0]
        if target == self.grammar.get("scopeName"):
            return {"include": "main"}
        return {"include": f"scope:{target}"}

    def _captures(self, captures: dict | None) -> dict:
        result = {}
        for key, capture in (captures or {}).items():
            if not isinstance(capture, dict):
                continue
            name = capture.get("name") or self._capture_scope(capture.get("patterns"))
            if name:
                result[int(key)] = self.scope(name)
        return result

    def _capture_scope(self, patterns: list | None) -> str | None:
        """The scope a capture's only pattern gives it whole, where that's known."""
        if not patterns or len(patterns) != 1 or "include" not in patterns[0]:
            return None
        target = patterns[0]["include"]
        if target in CAPTURE_SCOPES:
            return CAPTURE_SCOPES[target]
        entry = self.grammar.get("repository", {}).get(target.removeprefix("#"))
        if target.startswith("#") and entry and "match" in entry:
            return entry.get("name")
        return None

    def scope(self, name: str) -> str:
        return PLACEHOLDER.sub("", name)


def dump(value: object) -> str:
    """A scalar as YAML: strings double-quoted with JSON's escapes, which YAML 1.2 reads."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def emit(value: object, indent: int) -> list[str]:
    """A list of rules (or a rule's mapping) as block YAML."""
    pad = " " * indent
    lines: list[str] = []
    if isinstance(value, list):
        for item in value:
            if isinstance(item, dict):
                inner = emit(item, indent + 2)
                lines.append(pad + "- " + inner[0].lstrip())
                lines += inner[1:]
            else:
                lines.append(pad + "- " + dump(item))
        return lines
    assert isinstance(value, dict)
    for key, item in value.items():
        if isinstance(item, (dict, list)) and item:
            lines.append(f"{pad}{key}:")
            lines += emit(item, indent + 2)
        elif isinstance(item, (dict, list)):
            lines.append(f"{pad}{key}: []")
        else:
            lines.append(f"{pad}{key}: {dump(item)}")
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if an output is out of date"
    )
    args = parser.parse_args()

    stale = []
    for folder in sorted(p for p in GRAMMARS.iterdir() if p.is_dir()):
        meta = json.loads((folder / "meta.json").read_text(encoding="utf-8"))
        grammar = json.loads((folder / "source.json").read_text(encoding="utf-8"))
        converter = Converter(grammar, meta)
        text = converter.convert()
        output = folder / f"{folder.name}.sublime-syntax"
        for warning in converter.warnings:
            print(f"{folder.name}: {warning}", file=sys.stderr)
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != text:
                stale.append(output.relative_to(ROOT))
        else:
            output.write_text(text, encoding="utf-8")
            print(f"{output.relative_to(ROOT)}: {len(converter.contexts)} contexts")

    if stale:
        print(
            "out of date (run scripts/convert-grammars.py): "
            + ", ".join(map(str, stale)),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
